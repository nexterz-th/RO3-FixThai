using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Ro3Emu.DataExport;

namespace Ro3FixThai;

/// <summary>
/// The Thai text map for Ro3Loc, made from the player's own game files:
/// <list type="number">
/// <item>the client's Localization_zh_CN and Localization_th chunks (Recovery/LuaPayload), decoded with Ro3Emu.DataExport;</item>
/// <item>zh -> th for every id both tables hold (the most frequent Thai when one Chinese text has several); quest goals
/// carry a trailing '*' in the table that the client drops when it draws them, so both forms are kept;</item>
/// <item>extra translations (text no table holds), which win over the tables;</item>
/// <item>RO3Emu's English map: every Chinese text the Thai table lacks stays English.</item>
/// </list>
/// The output starts with RO3Emu's generated-map header, so "RO3Emu.exe join" copies it next to the game.
/// </summary>
public static class ThaiMap
{
    public const string Header = "# zh\ten - generated by RO3-FixThai: Thai (client Localization_th, English fallback)";

    private static readonly Regex Cjk = new("[\u2E80-\u9FFF\uF900-\uFAFF]");

    public sealed record Result(int Entries, int FromTables, int FromExtra, int StillEnglish);

    public static string ThaiChunk(string client) => Path.Combine(GameDataExport.LuaPayloadDir(client), "Localization_th.lua.bytes");

    public static Result Build(string client, string output, string? english, IEnumerable<(string Name, string Text)> extras, Action<string>? log = null)
    {
        var payload = GameDataExport.LuaPayloadDir(client);
        var work = Directory.CreateTempSubdirectory("ro3-fixthai-");
        try
        {
            var luac = Path.Combine(work.FullName, "luac");
            Directory.CreateDirectory(luac);
            foreach (var name in new[] { "Localization_zh_CN", "Localization_th" })
            {
                var source = Path.Combine(payload, name + ".lua.bytes");
                if (!File.Exists(source)) throw new FileNotFoundException($"this game has no {name} (a client with Thai is needed)", source);
                var bytes = File.ReadAllBytes(source);
                LuaChunkDecoder.Decode(bytes);
                File.WriteAllBytes(Path.Combine(luac, name + ".luac"), bytes);
            }
            var tables = Path.Combine(work.FullName, "tables");
            var errors = new List<string>();
            using (var exporter = new LuaConfigExporter(luac))
                exporter.ExportDirs(tables, ["Localization_zh_CN.luac", "Localization_th.luac"], errors.Add);
            foreach (var e in errors) log?.Invoke("  " + e);

            var zh = Texts(Path.Combine(tables, "Localization_zh_CN.json"));
            var th = Texts(Path.Combine(tables, "Localization_th.json"));

            var votes = new Dictionary<string, Dictionary<string, int>>(StringComparer.Ordinal);
            foreach (var (id, z) in zh)
            {
                if (!th.TryGetValue(id, out var t) || !Cjk.IsMatch(z) || string.IsNullOrWhiteSpace(t) || t == "None" || Cjk.IsMatch(t)) continue;
                if (!votes.TryGetValue(z, out var v)) votes[z] = v = new Dictionary<string, int>(StringComparer.Ordinal);
                v[t] = v.GetValueOrDefault(t) + 1;
            }
            var thai = votes.ToDictionary(p => p.Key, p => p.Value.OrderByDescending(x => x.Value).First().Key, StringComparer.Ordinal);
            foreach (var (z, t) in thai.ToList())
            {
                var bare = z.TrimEnd('*');
                if (bare != z && !thai.ContainsKey(bare)) thai[bare] = t.TrimEnd('*');
            }
            int fromTables = thai.Count, fromExtra = 0;
            foreach (var (_, text) in extras)
                foreach (var (z, t) in Pairs(text))
                {
                    thai[z] = t;
                    fromExtra++;
                }

            var map = new Dictionary<string, string>(StringComparer.Ordinal);
            int stillEnglish = 0;
            if (english != null && File.Exists(english))
                foreach (var (z, e) in Pairs(File.ReadAllText(english)))
                {
                    if (thai.TryGetValue(z, out var t)) map[z] = t;
                    else { map[z] = e; stillEnglish++; }
                }
            foreach (var (z, t) in thai) map.TryAdd(z, t);

            var sb = new StringBuilder(Header).Append('\n');
            foreach (var (z, t) in map) sb.Append(Escape(z)).Append('\t').Append(Escape(t)).Append('\n');
            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
            File.WriteAllText(output, sb.ToString(), new UTF8Encoding(false));
            return new Result(map.Count, fromTables, fromExtra, stillEnglish);
        }
        finally
        {
            work.Delete(recursive: true);
        }
    }

    /// <summary>"zh\ttext" lines of a map, unescaped; comments and blank lines skipped.</summary>
    public static IEnumerable<(string Zh, string Text)> Pairs(string tsv)
    {
        foreach (var raw in tsv.Split('\n'))
        {
            var line = raw.TrimEnd('\r');
            int tab = line.IndexOf('\t');
            if (line.Length == 0 || line[0] == '#' || tab <= 0) continue;
            yield return (Unescape(line[..tab]).TrimStart('\uFEFF'), Unescape(line[(tab + 1)..]));
        }
    }

    private static Dictionary<string, string> Texts(string json)
    {
        var texts = new Dictionary<string, string>();
        using var doc = JsonDocument.Parse(File.ReadAllText(json));
        foreach (var row in doc.RootElement.EnumerateObject())
            if (row.Value.ValueKind == JsonValueKind.Object && row.Value.TryGetProperty("_kDes", out var d) && d.ValueKind == JsonValueKind.String)
                texts[row.Name] = d.GetString()!;
        return texts;
    }

    private static string Unescape(string s) =>
        Regex.Replace(s, @"\\(.)", m => m.Groups[1].Value switch { "t" => "\t", "n" => "\n", "r" => "\r", var c => c });

    private static string Escape(string s) => s.Replace("\\", "\\\\").Replace("\t", "\\t").Replace("\r", "\\r").Replace("\n", "\\n");
}
